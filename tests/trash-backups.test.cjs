function backupFile(id) {
  const base = path.join(process.env.DONELINE_DIR, 'backups')
  for (const folder of fs.readdirSync(base)) {
    const file = path.join(base, folder, `${id}.doneline-backup.json`)
    if (fs.existsSync(file)) return file
  }
  throw new Error('Backup fixture file missing')
}

