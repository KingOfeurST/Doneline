test('backup is durable and restore is atomic, creates a safety copy, and keeps sync identity/calendar connections', () => {
  sync.installSyncJournal(db)
  const device = db.prepare('SELECT value FROM __sync_meta WHERE key = ?').get('device').value
  const row = task('Backed up task')
  core.setDailyNote('2026-10-10', 'Unicode café 🌙\nFinal line', me.id)
  db.prepare('INSERT INTO settings(key,value) VALUES (?,?)').run(`caldav:${me.id}`, 'current-private-connection')
  const remote = event('Backed up remote', { caldav_uid: 'remote-calendar-event', source: 'caldav' })
  const copy = core.createBackup()
  const parsed = JSON.parse(fs.readFileSync(backupFile(copy.id), 'utf8'))
  assert.equal(parsed.format, 'doneline-backup')
  assert.ok(!Object.keys(parsed.tables).some(name => name.startsWith('__sync_')))
  assert.equal(parsed.tables.calendar_tombstones, undefined)
  assert.equal(parsed.tables.calendar_resources, undefined)
  assert.equal(parsed.tables.calendar_resource_changes, undefined)
  assert.ok(!JSON.stringify(parsed).includes('current-private-connection'))
  core.updateTodo(row.id, { title: 'Newer current task' })
  const queued = db.prepare('SELECT operation_id FROM __sync_outbox ORDER BY seq DESC LIMIT 1').get().operation_id
  core.setDailyNote('2026-10-10', 'Current draft before restore', me.id)
  db.prepare('INSERT INTO calendar_tombstones(person_id,uid) VALUES (?,?)').run(me.id, 'historic-delete')
  const restored = core.restoreBackup(copy.id)
  assert.equal(core.getTodo(row.id).title, 'Backed up task')
  assert.equal(core.getDailyNote('2026-10-10', me.id).body, 'Unicode café 🌙\nFinal line')
  assert.equal(db.prepare('SELECT value FROM settings WHERE key = ?').get(`caldav:${me.id}`).value, 'current-private-connection')
  assert.equal(db.prepare('SELECT COUNT(*) n FROM calendar_tombstones').get().n, 0)
  assert.equal(core.getEvent(remote.id).calendar_restore, 1)
  assert.equal(core.getEvent(remote.id).calendar_dirty, 1)
  assert.equal(db.prepare('SELECT value FROM __sync_meta WHERE key = ?').get('device').value,device)
  assert.ok(db.prepare('SELECT 1 FROM __sync_outbox WHERE operation_id = ?').get(queued),'existing unacknowledged local changes remain queued')
  assert.ok(db.prepare("SELECT 1 FROM __sync_outbox WHERE table_name = 'todos' AND row_json LIKE ?").get('%Backed up task%'),'restore queues restored rows using normal sync triggers')
  assert.equal(restored.safetyBackup.reason, 'before-restore')
  const safety = JSON.parse(fs.readFileSync(backupFile(restored.safetyBackup.id), 'utf8'))
  const titles = safety.tables.todos.rows.map(row => row[safety.tables.todos.columns.indexOf('title')])
  assert.ok(titles.includes('Newer current task'))
  assert.throws(() => core.restoreBackup('../private.db'), /existing Doneline backup/)
  const child = require('node:child_process').spawnSync(process.execPath, ['-e', `const c=require(${JSON.stringify(compiled)}); c.restoreBackup(${JSON.stringify(copy.id)}); console.log(JSON.stringify(c.getTodo(${JSON.stringify(row.id)}))); c.closeDb()`],
    { env: process.env, encoding: 'utf8', windowsHide: true, timeout: 10000 })
  assert.equal(child.status, 0, child.stderr || child.error?.message)
  assert.equal(JSON.parse(child.stdout.trim().split(/\r?\n/).at(-1)).title, 'Backed up task', 'Backup restores into a fresh process without the original database')

  const corrupted = JSON.parse(fs.readFileSync(backupFile(copy.id), 'utf8'))
  const goal = core.createGoal({ title: 'Existing goal', person_id: me.id })
  const taskColumns = corrupted.tables.todos.columns
  corrupted.tables.todos.rows[0][taskColumns.indexOf('goal_id')] = 'missing-goal'
  fs.writeFileSync(backupFile(copy.id), JSON.stringify(corrupted))
  assert.throws(() => core.restoreBackup(copy.id), /FOREIGN KEY/)
  assert.ok(core.getGoal(goal.id), 'Failed restore rolled back every deleted table')
  assert.equal(core.getTodo(row.id).title, 'Backed up task')
  const forbidden = structuredClone(parsed)
  const keys = forbidden.tables.settings.columns
  forbidden.tables.settings.rows.push(keys.map(key=>key==='key'?`caldav:${friend.id}`:'historic-secret'))
  fs.writeFileSync(backupFile(copy.id), JSON.stringify(forbidden))
  assert.throws(() => core.restoreBackup(copy.id), /Calendar connections are managed separately/)
  assert.equal(db.prepare('SELECT value FROM settings WHERE key = ?').get(`caldav:${me.id}`).value, 'current-private-connection')
  assert.equal(db.prepare('SELECT value FROM settings WHERE key = ?').get(`caldav:${friend.id}`),undefined)
})

test('backup lists and daily snapshots are isolated to the active workspace database', () => {
  const localCopies = core.listBackups().map(copy=>copy.id)
  const child = require('node:child_process').spawnSync(process.execPath, ['-e', `const c=require(${JSON.stringify(compiled)}); const before=c.listBackups();c.getDb();const copy=c.ensureDailyBackup();console.log(JSON.stringify({before,copy,after:c.listBackups()}));c.closeDb();`],
    { env: { ...process.env,DONELINE_DB:path.join(directory,'other-private-workspace.db') },encoding:'utf8',windowsHide:true,timeout:10000 })
  assert.equal(child.status,0,child.stderr || child.error?.message)
  const result = JSON.parse(child.stdout.trim().split(/\r?\n/).at(-1))
  assert.deepEqual(result.before,[],'another database never offers backups from this workspace')
  assert.equal(result.after.length,1,'another workspace creates its own daily backup')
  assert.ok(!localCopies.includes(result.copy.id))
  assert.deepEqual(core.listBackups().map(copy=>copy.id),localCopies,'other workspace backup stays out of current list')
})

test('automatic backups are one per local day and older daily copies expire while manual copies stay', () => {
  const old = core.ensureDailyBackup(new Date('2026-01-01T12:00:00'))
  const manual = core.createBackup('manual', new Date('2026-01-01T13:00:00'))
  const current = core.ensureDailyBackup(new Date('2026-03-01T12:00:00'))
  const same = core.ensureDailyBackup(new Date('2026-03-01T22:00:00'))
  assert.equal(current.id, same.id)
  const copies = core.listBackups()
  assert.equal(copies.some(copy => copy.id === old.id), false)
  assert.equal(copies.some(copy => copy.id === manual.id), true)
})
